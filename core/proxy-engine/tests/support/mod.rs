//! Harness for the HTTP/1.1 and HTTPS proxying tests.
//!
//! Everything runs in this process on ephemeral ports: a proxy ([`Proxy`]),
//! a plaintext origin server ([`Origin`]), an HTTPS origin server
//! ([`TlsOrigin`]), a raw TCP server for a `CONNECT` to point at
//! ([`RawServer`]), a raw HTTP client ([`request`]), and an HTTPS client that
//! opens a `CONNECT` and then speaks TLS through it ([`HttpsClient`]).
//!
//! The servers and the clients speak HTTP over a socket by hand rather than
//! through an HTTP library. That is deliberate: these tests are about the
//! bytes the proxy puts on the wire — chunk framing, absent bodies, headers
//! that must not be forwarded, the exact status line that answers a
//! `CONNECT` — and a library on either end would normalise away the very
//! details under test. TLS is the exception: nobody hand-rolls a handshake,
//! so both TLS ends are built from `proxy-tls`, the same crate the proxy
//! uses.
//!
//! HTTP/2 is the second exception, and for the same reason TLS is: nobody
//! hand-rolls HPACK. The HTTP/2 ends of these tests — [`Http2Origin`] and
//! [`Http2Client`] — are built on the HTTP library, and what they assert is
//! what ProxyLab did with a stream rather than which bytes a frame was made
//! of. They live in [`super::support::http2`].
//!
//! # Which protocol a test end speaks
//!
//! Every TLS end here says so, over ALPN, and says only what it can actually
//! speak. The hand-written HTTP/1.1 ends offer `http/1.1` alone, so a proxy
//! talking to one settles on HTTP/1.1 and its assertions stay about the bytes
//! it wrote. The HTTP/2 ends offer `h2` alone. Only the proxy offers both,
//! which is exactly the arrangement a real client and a real origin put it
//! in.
//!
//! Every certificate here is generated by the test that needs it, from a CA
//! generated for that test. Nothing reads, writes, or trusts the development
//! CA a developer has installed, and nothing reaches the network: no external
//! service and no fixed port. Host names are `localhost` and loopback
//! addresses only.

