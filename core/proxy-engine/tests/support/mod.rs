/// Long enough to absorb a loaded machine, short enough that a proxy which
/// never answers fails the test instead of hanging it.
pub const TEST_TIMEOUT: Duration = Duration::from_secs(5);

/// Port `0` asks the operating system for a free port, so the tests never
/// depend on a particular port being available.
const EPHEMERAL: &str = "127.0.0.1:0";

/// A CA generated for one test and thrown away with it.
///
/// Never the developer's own: no test reads or writes a stored CA, so a test
/// run cannot disturb, or come to depend on, a CA that is installed in a
/// trust store somewhere.
fn generated_ca() -> CertificateAuthority {
    CertificateAuthority::generate().expect("generate a CA")
}

/// Trust in exactly one CA's certificate, and nothing else.
pub(crate) fn trusting(authority: &CertificateAuthority) -> UpstreamTrust {
    UpstreamTrust::Certificates(vec![authority.certificate_der().clone()])
}

/// Trust in every CA `trusts` name, and nothing else.
///
/// For a test with two TLS origins in it — a session opened to one and a rule
/// mapping the request to another — where the proxy has to verify both.
pub fn trusting_all(trusts: &[UpstreamTrust]) -> UpstreamTrust {
    let certificates = trusts
        .iter()
        .flat_map(|trust| match trust {
            UpstreamTrust::Certificates(certificates) => certificates.clone(),
            UpstreamTrust::PublicRoots => Vec::new(),
        })
        .collect();

    UpstreamTrust::Certificates(certificates)
}

/// The only protocol the hand-written HTTP/1.1 ends of these tests can speak.
///
/// They read a request line and write a status line, so a session that
/// settled on `h2` would hand them a connection preface and they would make
/// nonsense of it. Saying so over ALPN is what a real HTTP/1.1-only peer
/// does, and is what keeps these tests about HTTP/1.1.
pub const HTTP_1_1_ONLY: &[Protocol] = &[Protocol::Http11];

/// An interceptor of the kind the proxy builds, with a CA of its own.
///
/// For the tests that exercise a part of the pipeline directly rather than
/// through the listening socket — replay, which has no socket of its own.
/// The CA is generated for the call and thrown away with it, so nothing here
/// touches a CA a developer has installed.
pub fn interceptor(trust: UpstreamTrust) -> Arc<Interceptor> {
    Arc::new(Interceptor::new(generated_ca(), &trust).expect("build an interceptor"))
}

/// The proxy under test, listening on an OS-chosen port.
pub struct Proxy {
    addr: SocketAddr,
    interceptor: Arc<Interceptor>,
    upstream: Arc<UpstreamManager>,
    capture: Capture,
    rules: Arc<RuleEngine>,
    controls: Controls,
    shutdown: Option<oneshot::Sender<()>>,
    task: Option<JoinHandle<io::Result<()>>>,
}

impl Proxy {
    /// Starts the real listener, with a CA of its own and no private trust.
    ///
    /// Nothing this proxy connects to in these tests is signed by a public
    /// root, so this is the proxy to point at an origin whose certificate
    /// should be refused.
    pub async fn start() -> Self {
        Self::trusting(UpstreamTrust::PublicRoots).await
    }

    /// Starts the real listener, verifying origin servers against `trust`.
    pub async fn trusting(trust: UpstreamTrust) -> Self {
        Self::capturing(trust, Capture::with_defaults()).await
    }

    /// Starts the real listener with a capture of the test's choosing and no
    /// private trust, for the plaintext tests, which never reach a TLS
    /// origin.
    pub async fn with_capture(capture: Capture) -> Self {
        Self::capturing(UpstreamTrust::PublicRoots, capture).await
    }

    /// Starts the real listener with a capture of the test's choosing, which
    /// is how a test sets the body limit it wants to see the effect of.
    pub async fn capturing(trust: UpstreamTrust, capture: Capture) -> Self {
        Self::ruled(trust, capture, RuleSet::empty()).await
    }

    /// Starts the real listener with `rules` in force.
    ///
    /// The engine is the same one the binary builds, so a test exercises the
    /// path a running proxy takes rather than a test-only shortcut.
    pub async fn ruled(trust: UpstreamTrust, capture: Capture, rules: RuleSet) -> Self {
        Self::pooling(trust, capture, rules, PoolLimits::default()).await
    }

    /// Starts the real listener with `limits` on its upstream connection pool.
    ///
    /// The pooling tests are the reason this exists: the defaults are what a
    /// running proxy uses, and a test that wants to see a limit take effect
    /// needs a smaller one it can reach.
    pub async fn pooling(
        trust: UpstreamTrust,
        capture: Capture,
        rules: RuleSet,
        limits: PoolLimits,
    ) -> Self {
        Self::launch(trust, capture, rules, limits, false).await
    }

    /// Starts the transparent capture bridge rather than the explicit proxy:
    /// the listener the Network Extension's provider hands flows to.
    ///
    /// It is the same `Listener`, with the same interceptor, pool, capture,
    /// rules and controls, and it counts this test process as its own — which
    /// it is, since the bridge is running in it.
    pub async fn bridge(trust: UpstreamTrust, rules: RuleSet) -> Self {
        Self::launch(
            trust,
            Capture::with_defaults(),
            rules,
            PoolLimits::default(),
            true,
        )
        .await
    }

    async fn launch(
        trust: UpstreamTrust,
        capture: Capture,
        rules: RuleSet,
        limits: PoolLimits,
        transparent: bool,
    ) -> Self {
        let engine = Arc::new(RuleEngine::with(rules));
        let interceptor =
            Arc::new(Interceptor::new(generated_ca(), &trust).expect("build an interceptor"));
        let upstream = Arc::new(UpstreamManager::with_limits(
            Arc::clone(&interceptor),
            limits,
        ));
        let listener = Listener::bind(EPHEMERAL)
            .await
            .expect("bind ephemeral port");
        let addr = listener.local_addr();
        let listener = if transparent {
            listener.transparent(Own::this_process(&[addr]))
        } else {
            listener
        };
        let (shutdown, signal) = oneshot::channel();
        let running = Arc::clone(&interceptor);
        let connecting = Arc::clone(&upstream);
        let recording = capture.clone();
        let ruling = Arc::clone(&engine);
        let controls = Controls::new();
        let controlling = controls.clone();
        let task = tokio::spawn(async move {
            listener
                .run(
                    running,
                    connecting,
                    recording,
                    Some(ruling),
                    controlling,
                    async {
                        let _ = signal.await;
                    },
                )
                .await
        });

        Self {
            addr,
            interceptor,
            upstream,
            capture,
            rules: engine,
            controls,
            shutdown: Some(shutdown),
            task: Some(task),
        }
    }

    /// The breakpoints and the throttling this proxy is running with.
    ///
    /// The same handle the IPC server would be given, so a test configures a
    /// breakpoint or a bandwidth ceiling exactly as the UI does.
    pub fn controls(&self) -> &Controls {
        &self.controls
    }

    /// Replaces the rules this proxy is applying, as an IPC change would.
    pub fn set_rules(&self, rules: RuleSet) {
        self.rules.replace(rules);
    }

    /// The address clients send proxy requests to.
    pub fn addr(&self) -> SocketAddr {
        self.addr
    }

    /// What a client has to trust to accept this proxy's certificates.
    pub fn trust(&self) -> UpstreamTrust {
        trusting(self.interceptor.authority())
    }

    /// Starts listening for the exchanges the proxy publishes.
    ///
    /// Subscribe before sending a request: a subscriber receives what is
    /// published after it attaches, and nothing before.
    pub fn events(&self) -> EventSubscriber {
        self.capture.subscribe()
    }

    /// The capture the proxy is recording into.
    pub fn capture(&self) -> &Capture {
        &self.capture
    }

    /// The engine the proxy consults.
    pub fn rules(&self) -> &RuleEngine {
        &self.rules
    }

    /// The same engine, shared.
    ///
    /// What the binary hands a `Replayer`, so a test that stands one up
    /// beside this proxy gives it the rules this listener is applying rather
    /// than a second set of them.
    pub fn engine(&self) -> Arc<RuleEngine> {
        Arc::clone(&self.rules)
    }

    /// How many hosts the proxy has minted certificates for.
    pub fn certified_hosts(&self) -> usize {
        self.interceptor.cached_hosts()
    }

    /// The connections the proxy is holding open to origin servers.
    pub fn upstream(&self) -> &Arc<UpstreamManager> {
        &self.upstream
    }

    /// The interceptor this proxy is using, for a test that has to hand the
    /// same one to something else — a second listener over the same
    /// pipeline, which is what LAN exposure is.
    pub fn interceptor(&self) -> &Arc<Interceptor> {
        &self.interceptor
    }

    /// The engine as something shareable, for the same reason.
    pub fn rule_engine(&self) -> &Arc<RuleEngine> {
        &self.rules
    }

    /// The certificate of the CA this proxy mints from, as PEM.
    ///
    /// What a device would have to install. A test uses it to check that
    /// what the setup page serves is this proxy's own CA and not some other
    /// bytes of the right shape.
    pub fn ca_certificate_pem(&self) -> String {
        self.interceptor.authority().certificate_pem().to_owned()
    }

    /// How many idle upstream HTTP/1.1 connections the proxy is holding.
    pub fn idle_upstream_connections(&self) -> usize {
        self.upstream.pool().idle_count()
    }

    /// Signals shutdown and waits up to `limit` for the accept loop.
    ///
    /// For the tests that are about how long stopping takes. `stop` waits the
    /// ordinary test timeout, which is the same as the listener's own grace
    /// period and so cannot tell "stopped within it" from "did not".
    pub async fn stop_within(mut self, limit: Duration) {
        if let Some(shutdown) = self.shutdown.take() {
            let _ = shutdown.send(());
        }

        if let Some(task) = self.task.take() {
            timeout(limit, task)
                .await
                .expect("the proxy stops within the limit")
                .expect("proxy task does not panic")
                .expect("clean shutdown");
        }
    }

    /// Signals shutdown and waits for the accept loop to finish.
    pub async fn stop(mut self) {
        if let Some(shutdown) = self.shutdown.take() {
            let _ = shutdown.send(());
        }

        if let Some(task) = self.task.take() {
            timeout(TEST_TIMEOUT, task)
                .await
                .expect("proxy shuts down")
                .expect("proxy task does not panic")
                .expect("clean shutdown");
        }
    }
}

impl Drop for Proxy {
    fn drop(&mut self) {
        if let Some(shutdown) = self.shutdown.take() {
            let _ = shutdown.send(());
        }
    }
}

/// A request as the origin server received it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RecordedRequest {
    pub method: String,
    pub target: String,
    pub version: String,
    /// Header names lowercased, values as sent, in the order received.
    pub headers: Vec<(String, String)>,
    pub body: Vec<u8>,
}

impl RecordedRequest {
    /// First value of `name`, or `None` if the header was not sent.
    pub fn header(&self, name: &str) -> Option<&str> {
        self.headers
            .iter()
            .find(|(header, _)| header == name)
            .map(|(_, value)| value.as_str())
    }

    /// The body as text.
    pub fn body_text(&self) -> String {
        String::from_utf8(self.body.clone()).expect("text body")
    }
}

/// An in-process HTTP origin server that answers with canned bytes.
pub struct Origin {
    addr: SocketAddr,
    requests: Arc<Mutex<Vec<RecordedRequest>>>,
    task: JoinHandle<()>,
}

impl Origin {
    /// Starts an origin whose reply to every request is `response`.
    pub async fn responding_with(response: &'static [u8]) -> Self {
        Self::start(move |_| response.to_vec()).await
    }

    /// Starts an origin that builds its reply from the request it received.
    pub async fn start<R>(responder: R) -> Self
    where
        R: Fn(&RecordedRequest) -> Vec<u8> + Send + Sync + 'static,
    {
        let listener = TcpListener::bind(EPHEMERAL)
            .await
            .expect("bind ephemeral port");
        let addr = listener.local_addr().expect("local address");
        let requests = Arc::new(Mutex::new(Vec::new()));

        let responder = Arc::new(responder);
        let recorded = Arc::clone(&requests);
        let task = tokio::spawn(async move {
            while let Ok((stream, _)) = listener.accept().await {
                let responder = Arc::clone(&responder);
                let recorded = Arc::clone(&recorded);
                tokio::spawn(async move {
                    let _ = serve_origin_connection(stream, responder, recorded).await;
                });
            }
        });

        Self {
            addr,
            requests,
            task,
        }
    }

    /// The address the origin is listening on.
    pub fn addr(&self) -> SocketAddr {
        self.addr
    }

    /// A `http://host:port` prefix for building absolute request targets.
    pub fn base_url(&self) -> String {
        format!("http://{}", self.addr)
    }

    /// Every request the origin has received so far.
    pub fn requests(&self) -> Vec<RecordedRequest> {
        self.requests.lock().expect("requests are readable").clone()
    }

    /// The single request the origin received.
    pub fn only_request(&self) -> RecordedRequest {
        let mut requests = self.requests();

        assert_eq!(requests.len(), 1, "expected exactly one origin request");
        requests.remove(0)
    }
}

impl Drop for Origin {
    fn drop(&mut self) {
        self.task.abort();
    }
}

/// Reads one request, records it, and writes the responder's bytes back.
///
/// Generic over the stream, so the same exchange serves a plain socket and
/// the server side of a TLS session.
async fn serve_origin_connection<S, R>(
    stream: S,
    responder: Arc<R>,
    recorded: Arc<Mutex<Vec<RecordedRequest>>>,
) -> io::Result<()>
where
    S: AsyncRead + AsyncWrite + Unpin,
    R: Fn(&RecordedRequest) -> Vec<u8> + Send + Sync + 'static,
{
    let mut reader = BufReader::new(stream);
    let Some(request) = read_request(&mut reader).await? else {
        return Ok(());
    };

    let response = responder(&request);
    recorded
        .lock()
        .expect("requests are writable")
        .push(request);

    let mut stream = reader.into_inner();
    stream.write_all(&response).await?;
    stream.flush().await?;
    stream.shutdown().await
}

/// Parses one HTTP/1.1 request, including its body if it has one.
async fn read_request<S>(reader: &mut BufReader<S>) -> io::Result<Option<RecordedRequest>>
where
    S: AsyncRead + Unpin,
{
    let Some(request_line) = read_line(reader).await? else {
        return Ok(None);
    };

    let mut parts = request_line.split(' ');
    let method = parts.next().unwrap_or_default().to_owned();
    let target = parts.next().unwrap_or_default().to_owned();
    let version = parts.next().unwrap_or_default().to_owned();

    let mut headers = Vec::new();
    while let Some(line) = read_line(reader).await? {
        if line.is_empty() {
            break;
        }

        if let Some((name, value)) = line.split_once(':') {
            headers.push((name.trim().to_ascii_lowercase(), value.trim().to_owned()));
        }
    }

    let body = read_body(reader, &headers).await?;

    Ok(Some(RecordedRequest {
        method,
        target,
        version,
        headers,
        body,
    }))
}

/// Reads a body framed either by `Transfer-Encoding: chunked` or by
/// `Content-Length`. Anything else is a request with no body.
async fn read_body<S>(
    reader: &mut BufReader<S>,
    headers: &[(String, String)],
) -> io::Result<Vec<u8>>
where
    S: AsyncRead + Unpin,
{
    let value = |name: &str| {
        headers
            .iter()
            .find(|(header, _)| header == name)
            .map(|(_, value)| value.as_str())
    };

    if value("transfer-encoding").is_some_and(|coding| coding.contains("chunked")) {
        return read_chunked_body(reader).await;
    }

    let length: usize = match value("content-length").and_then(|value| value.parse().ok()) {
        Some(length) => length,
        None => return Ok(Vec::new()),
    };

    let mut body = vec![0_u8; length];
    reader.read_exact(&mut body).await?;

    Ok(body)
}

/// Reads a chunked body down to, and including, the terminating chunk.
async fn read_chunked_body<S>(reader: &mut BufReader<S>) -> io::Result<Vec<u8>>
where
    S: AsyncRead + Unpin,
{
    let mut body = Vec::new();

    loop {
        let Some(size_line) = read_line(reader).await? else {
            break;
        };
        let size = usize::from_str_radix(size_line.split(';').next().unwrap_or("0").trim(), 16)
            .map_err(|_| io::Error::new(io::ErrorKind::InvalidData, "bad chunk size"))?;

        if size == 0 {
            // Trailer section, empty in these tests, ends with a blank line.
            while let Some(line) = read_line(reader).await? {
                if line.is_empty() {
                    break;
                }
            }
            break;
        }

        let mut chunk = vec![0_u8; size];
        reader.read_exact(&mut chunk).await?;
        body.extend_from_slice(&chunk);

        let mut crlf = [0_u8; 2];
        reader.read_exact(&mut crlf).await?;
    }

    Ok(body)
}

/// Reads one CRLF-terminated line, or `None` at end of stream.
async fn read_line<R>(reader: &mut R) -> io::Result<Option<String>>
where
    R: AsyncBufRead + Unpin,
{
    let mut line = Vec::new();
    if reader.read_until(b'\n', &mut line).await? == 0 {
        return Ok(None);
    }

    while line
        .last()
        .is_some_and(|byte| *byte == b'\n' || *byte == b'\r')
    {
        line.pop();
    }

    String::from_utf8(line)
        .map(Some)
        .map_err(|_| io::Error::new(io::ErrorKind::InvalidData, "non-text header line"))
}

/// A response as the client received it, before any decoding.
#[derive(Debug, Clone)]
pub struct RawResponse {
    pub status_line: String,
    pub status: u16,
    /// Header names lowercased, values as received, in the order received.
    pub headers: Vec<(String, String)>,
    /// The body exactly as framed on the wire, chunk headers included.
    pub framed_body: Vec<u8>,
}

impl RawResponse {
    /// First value of `name`, or `None` if the header was not received.
    pub fn header(&self, name: &str) -> Option<&str> {
        self.headers
            .iter()
            .find(|(header, _)| header == name)
            .map(|(_, value)| value.as_str())
    }

    /// Whether the response was framed with chunked transfer coding.
    pub fn is_chunked(&self) -> bool {
        self.header("transfer-encoding")
            .is_some_and(|coding| coding.contains("chunked"))
    }

    /// The body with any chunk framing removed.
    pub fn body(&self) -> Vec<u8> {
        if self.is_chunked() {
            dechunk(&self.framed_body)
        } else {
            self.framed_body.clone()
        }
    }

    /// The decoded body as text.
    pub fn body_text(&self) -> String {
        String::from_utf8(self.body()).expect("text body")
    }
}

/// Sends raw bytes to the proxy and reads the whole response, up to the close.
pub async fn send_raw(proxy: SocketAddr, request: &[u8]) -> RawResponse {
    let bytes = timeout(TEST_TIMEOUT, async {
        let mut stream = TcpStream::connect(proxy).await?;
        stream.write_all(request).await?;
        stream.flush().await?;

        let mut response = Vec::new();
        stream.read_to_end(&mut response).await?;

        io::Result::Ok(response)
    })
    .await
    .expect("proxy answers and closes the connection")
    .expect("exchange with the proxy");

    parse_response(&bytes)
}

/// Sends a proxy request with no body.
pub async fn request(
    proxy: SocketAddr,
    method: &str,
    url: &str,
    headers: &[(&str, &str)],
) -> RawResponse {
    send_raw(proxy, &build_request(method, url, headers, None)).await
}

/// Sends a proxy request whose body is framed with `Content-Length`.
pub async fn request_with_body(
    proxy: SocketAddr,
    method: &str,
    url: &str,
    headers: &[(&str, &str)],
    body: &str,
) -> RawResponse {
    send_raw(proxy, &build_request(method, url, headers, Some(body))).await
}

/// Builds the bytes of a proxy request in absolute form.
fn build_request(method: &str, url: &str, headers: &[(&str, &str)], body: Option<&str>) -> Vec<u8> {
    let authority = url
        .strip_prefix("http://")
        .and_then(|rest| rest.split('/').next())
        .unwrap_or_default();

    let mut request = format!("{method} {url} HTTP/1.1\r\nHost: {authority}\r\n");
    for (name, value) in headers {
        request.push_str(&format!("{name}: {value}\r\n"));
    }
    if let Some(body) = body {
        request.push_str(&format!("Content-Length: {}\r\n", body.len()));
    }
    request.push_str("\r\n");
    if let Some(body) = body {
        request.push_str(body);
    }

    request.into_bytes()
}

/// Splits a response into its status line, headers, and framed body.
fn parse_response(bytes: &[u8]) -> RawResponse {
    let split = bytes
        .windows(4)
        .position(|window| window == b"\r\n\r\n")
        .expect("response has a header section");
    let head = String::from_utf8(bytes[..split].to_vec()).expect("text response head");
    let framed_body = bytes[split + 4..].to_vec();

    let mut lines = head.split("\r\n");
    let status_line = lines.next().unwrap_or_default().to_owned();
    let status = status_line
        .split(' ')
        .nth(1)
        .and_then(|code| code.parse().ok())
        .expect("status line has a status code");

    let headers = lines
        .filter_map(|line| line.split_once(':'))
        .map(|(name, value)| (name.trim().to_ascii_lowercase(), value.trim().to_owned()))
        .collect();

    RawResponse {
        status_line,
        status,
        headers,
        framed_body,
    }
}

/// Removes chunk framing from a chunked body.
fn dechunk(framed: &[u8]) -> Vec<u8> {
    let mut body = Vec::new();
    let mut rest = framed;

    while let Some(end_of_size) = rest.windows(2).position(|window| window == b"\r\n") {
        let size_line = String::from_utf8(rest[..end_of_size].to_vec()).expect("text chunk size");
        let size = usize::from_str_radix(size_line.split(';').next().unwrap_or("0").trim(), 16)
            .expect("chunk size is hexadecimal");

        if size == 0 {
            break;
        }

        let start = end_of_size + 2;
        body.extend_from_slice(&rest[start..start + size]);
        rest = &rest[start + size + 2..];
    }

    body
}

/// An in-process raw TCP server, for a `CONNECT` tunnel to point at.
///
/// It speaks no protocol at all: each accepted connection is handed to the
/// handler the test supplied, which reads and writes bytes as it likes. That
/// is the point — what a tunnel carries is opaque, so the far end of one
/// must be too.
pub struct RawServer {
    addr: SocketAddr,
    task: JoinHandle<()>,
}

impl RawServer {
    /// Starts a server that runs `handler` on every connection it accepts.
    ///
    /// Each connection gets its own task, so a handler that blocks on one
    /// connection does not stop the others being served.
    pub async fn start<H, F>(handler: H) -> Self
    where
        H: Fn(TcpStream) -> F + Send + Sync + 'static,
        F: Future<Output = ()> + Send + 'static,
    {
        let listener = TcpListener::bind(EPHEMERAL)
            .await
            .expect("bind ephemeral port");
        let addr = listener.local_addr().expect("local address");

        let handler = Arc::new(handler);
        let task = tokio::spawn(async move {
            while let Ok((stream, _)) = listener.accept().await {
                let handler = Arc::clone(&handler);
                tokio::spawn(async move { handler(stream).await });
            }
        });

        Self { addr, task }
    }

    /// Starts a server that sends back whatever it is sent.
    pub async fn echoing() -> Self {
        Self::start(|mut stream| async move {
            let (mut from_client, mut to_client) = stream.split();
            let _ = tokio::io::copy(&mut from_client, &mut to_client).await;
            let _ = to_client.shutdown().await;
        })
        .await
    }

    /// The address the server is listening on.
    pub fn addr(&self) -> SocketAddr {
        self.addr
    }

    /// The `host:port` a `CONNECT` request should name to reach it.
    pub fn authority(&self) -> String {
        self.addr.to_string()
    }
}

impl Drop for RawServer {
    fn drop(&mut self) {
        self.task.abort();
    }
}

/// A tunnel opened through the proxy.
pub struct Tunnel {
    /// The response that opened it, head only.
    pub response: RawResponse,
    /// The client's socket, now carrying raw bytes rather than HTTP.
    pub stream: TcpStream,
}

/// Sends a `CONNECT` for `target` and reads back only the response head.
///
/// Reading stops at the blank line that ends the head, so nothing the far
/// side has already sent through the tunnel is swallowed by the client that
/// is about to read it.
pub async fn connect_tunnel(proxy: SocketAddr, target: &str) -> Tunnel {
    open_tunnel(proxy, &connect_request(target)).await
}

/// Sends `request`, which is a `CONNECT` of the test's own writing, and reads
/// back only the response head — for a `CONNECT` carrying a header the
/// ordinary one does not.
pub async fn open_tunnel(proxy: SocketAddr, request: &[u8]) -> Tunnel {
    let (response, stream) = timeout(TEST_TIMEOUT, async {
        let mut stream = TcpStream::connect(proxy).await?;
        stream.write_all(request).await?;
        stream.flush().await?;

        let head = read_head(&mut stream).await?;

        io::Result::Ok((head, stream))
    })
    .await
    .expect("proxy answers the CONNECT")
    .expect("exchange with the proxy");

    Tunnel {
        response: parse_response(&response),
        stream,
    }
}

/// The bytes of a `CONNECT` request for `target`.
pub fn connect_request(target: &str) -> Vec<u8> {
    format!("CONNECT {target} HTTP/1.1\r\nHost: {target}\r\n\r\n").into_bytes()
}

/// Reads up to and including the blank line that ends a response head.
///
/// One byte at a time, so not a single byte of what follows the head — which
/// belongs to the tunnel — is read into this buffer.
async fn read_head(stream: &mut TcpStream) -> io::Result<Vec<u8>> {
    let mut head = Vec::new();
    let mut byte = [0_u8; 1];

    while stream.read(&mut byte).await? == 1 {
        head.push(byte[0]);

        if head.ends_with(b"\r\n\r\n") {
            break;
        }
    }

    Ok(head)
}

/// An in-process HTTPS origin server.
///
/// TLS first, then one HTTP/1.1 exchange per connection, exactly as the
/// plaintext [`Origin`] does — the only difference is the session the bytes
/// travel in. Its certificate is signed by a CA generated for this server, so
/// a proxy reaching it has to be told to trust that CA; a proxy that is not
/// told refuses the certificate, which is what several of these tests are
/// about.
///
/// It listens on `localhost`, and its certificate names `localhost`, so a
/// proxy connecting to it verifies a real host name against a real subject
/// alternative name.
pub struct TlsOrigin {
    addr: SocketAddr,
    host: String,
    interceptor: Arc<Interceptor>,
    requests: Arc<Mutex<Vec<RecordedRequest>>>,
    task: JoinHandle<()>,
}

impl TlsOrigin {
    /// Starts an origin, listening as `host`, whose reply to every request is
    /// `response`.
    pub async fn responding_with(host: &str, response: &'static [u8]) -> Self {
        Self::start(host, move |_| response.to_vec()).await
    }

    /// Starts an origin, listening as `host`, that builds its reply from the
    /// request it received.
    pub async fn start<R>(host: &str, responder: R) -> Self
    where
        R: Fn(&RecordedRequest) -> Vec<u8> + Send + Sync + 'static,
    {
        let interceptor = Arc::new(
            Interceptor::offering(generated_ca(), &UpstreamTrust::PublicRoots, HTTP_1_1_ONLY)
                .expect("build an interceptor"),
        );
        // Binding by name, and connecting by the same name, means the test
        // and the proxy resolve `localhost` the same way — whichever loopback
        // address that turns out to be on this machine.
        let listener = TcpListener::bind((host, 0))
            .await
            .expect("bind ephemeral port");
        let addr = listener.local_addr().expect("local address");
        let requests = Arc::new(Mutex::new(Vec::new()));

        let responder = Arc::new(responder);
        let recorded = Arc::clone(&requests);
        let serving = Arc::clone(&interceptor);
        let name = tls_host(host);
        let task = tokio::spawn(async move {
            while let Ok((stream, _)) = listener.accept().await {
                let responder = Arc::clone(&responder);
                let recorded = Arc::clone(&recorded);
                let serving = Arc::clone(&serving);
                let name = name.clone();
                tokio::spawn(async move {
                    let Ok(session) = serving.accept_client(&name, stream).await else {
                        return;
                    };

                    let _ = serve_origin_connection(session, responder, recorded).await;
                });
            }
        });

        Self {
            addr,
            host: host.to_owned(),
            interceptor,
            requests,
            task,
        }
    }

    /// The `host:port` a `CONNECT` request should name to reach it.
    pub fn authority(&self) -> String {
        format!("{}:{}", self.host, self.addr.port())
    }

    /// The address it is listening on, which is what a transparently
    /// captured flow to it names: the application resolved the name, and
    /// connected to what came back.
    pub fn addr(&self) -> SocketAddr {
        self.addr
    }

    /// The host name its certificate is issued for.
    pub fn host(&self) -> &str {
        &self.host
    }

    /// What a proxy has to trust to accept this origin's certificate.
    pub fn trust(&self) -> UpstreamTrust {
        trusting(self.interceptor.authority())
    }

    /// Every request the origin has received so far.
    pub fn requests(&self) -> Vec<RecordedRequest> {
        self.requests.lock().expect("requests are readable").clone()
    }

    /// The single request the origin received.
    pub fn only_request(&self) -> RecordedRequest {
        let mut requests = self.requests();

        assert_eq!(requests.len(), 1, "expected exactly one origin request");
        requests.remove(0)
    }
}

impl Drop for TlsOrigin {
    fn drop(&mut self) {
        self.task.abort();
    }
}

/// An in-process TLS server that presents a certificate and nothing else.
///
/// For the case where the origin's certificate is the thing under test: it
/// completes a handshake with anyone who trusts its CA, and there is no HTTP
/// behind it because no test that uses it gets that far.
pub struct UntrustedTlsOrigin {
    addr: SocketAddr,
    host: String,
    task: JoinHandle<()>,
}

impl UntrustedTlsOrigin {
    /// Starts a TLS server listening as `host` whose CA nobody is told about.
    pub async fn start(host: &str) -> Self {
        let interceptor = Arc::new(
            Interceptor::offering(generated_ca(), &UpstreamTrust::PublicRoots, HTTP_1_1_ONLY)
                .expect("build an interceptor"),
        );
        let listener = TcpListener::bind((host, 0))
            .await
            .expect("bind ephemeral port");
        let addr = listener.local_addr().expect("local address");
        let name = tls_host(host);

        let task = tokio::spawn(async move {
            while let Ok((stream, _)) = listener.accept().await {
                let interceptor = Arc::clone(&interceptor);
                let name = name.clone();
                tokio::spawn(async move {
                    let _ = interceptor.accept_client(&name, stream).await;
                });
            }
        });

        Self {
            addr,
            host: host.to_owned(),
            task,
        }
    }

    /// The `host:port` a `CONNECT` request should name to reach it.
    pub fn authority(&self) -> String {
        format!("{}:{}", self.host, self.addr.port())
    }
}

impl Drop for UntrustedTlsOrigin {
    fn drop(&mut self) {
        self.task.abort();
    }
}

/// An HTTPS client that reaches origins through the proxy.
///
/// It does what curl does: `CONNECT host:port`, then a TLS handshake on the
/// same socket, then an HTTP/1.1 request inside the session. What it trusts
/// is given to it, so a test can be a client that has installed the proxy's
/// development CA or one that has not.
pub struct HttpsClient {
    interceptor: Interceptor,
}

impl HttpsClient {
    /// A client that accepts certificates chaining to `trust`.
    ///
    /// It offers only `http/1.1`, because it writes HTTP/1.1 by hand: a
    /// client that asked for `h2` and then sent a request line would be a
    /// client lying about itself. [`super::support::http2::Http2Client`] is
    /// the one that asks for HTTP/2.
    pub fn trusting(trust: UpstreamTrust) -> Self {
        Self {
            interceptor: Interceptor::offering(generated_ca(), &trust, HTTP_1_1_ONLY)
                .expect("build an interceptor"),
        }
    }

    /// A client that trusts only the public web PKI.
    ///
    /// No locally generated CA is in that store, so this client refuses every
    /// certificate the proxy can present — which is the point of the tests
    /// that use it.
    pub fn trusting_nothing_local() -> Self {
        Self::trusting(UpstreamTrust::PublicRoots)
    }

    /// Opens a `CONNECT` to `authority` and completes the TLS handshake.
    ///
    /// The `Err` is the client's own view of a refused handshake, which is
    /// what a client that has not installed the CA sees.
    pub async fn connect(
        &self,
        proxy: SocketAddr,
        authority: &str,
        host: &str,
    ) -> (RawResponse, Result<Session, TlsError>) {
        let tunnel = connect_tunnel(proxy, authority).await;
        let session = timeout(
            TEST_TIMEOUT,
            self.interceptor
                .connect_upstream(&tls_host(host), tunnel.stream),
        )
        .await
        .expect("the handshake finishes, one way or the other");

        (tunnel.response, session)
    }

    /// The whole exchange: `CONNECT`, handshake, one request, read the answer.
    ///
    /// Reading runs to the end of the stream, which the proxy reaches by
    /// declaring the response the last on its connection — so the response
    /// that comes back is complete, and getting there proves the session was
    /// closed rather than abandoned.
    pub async fn exchange(
        &self,
        proxy: SocketAddr,
        authority: &str,
        host: &str,
        request: &[u8],
    ) -> RawResponse {
        let (connect, session) = self.connect(proxy, authority, host).await;

        assert_eq!(
            connect.status, 200,
            "the proxy refused the CONNECT: {}",
            connect.status_line
        );

        let mut session = session.expect("the client accepts the proxy's certificate");
        let answer = timeout(TEST_TIMEOUT, async {
            session.write_all(request).await?;
            session.flush().await?;

            let mut answer = Vec::new();
            session.read_to_end(&mut answer).await?;

            io::Result::Ok(answer)
        })
        .await
        .expect("the origin answers and the session closes")
        .expect("exchange inside the intercepted session");

        parse_response(&answer)
    }
}

/// An intercepted TLS session, from the client's side of it.
pub type Session = UpstreamSession<TcpStream>;

/// The host name a TLS session is for.
fn tls_host(host: &str) -> Host {
    Host::parse(host).expect("usable host")
}

/// The bytes of an HTTP/1.1 request as sent inside an intercepted session.
///
/// Origin form, because that is what a client that believes it is talking to
/// the origin sends.
pub fn origin_form_request(
    method: &str,
    path: &str,
    host: &str,
    headers: &[(&str, &str)],
) -> Vec<u8> {
    let mut request = format!("{method} {path} HTTP/1.1\r\nHost: {host}\r\n");
    for (name, value) in headers {
        request.push_str(&format!("{name}: {value}\r\n"));
    }
    request.push_str("\r\n");

    request.into_bytes()
}

/// The next exchange the proxy publishes.
///
/// Waits rather than polls, so a test never depends on how quickly the proxy
/// finishes with a response; a proxy that publishes nothing fails the test
/// instead of hanging it.
pub async fn next_exchange(subscriber: &mut EventSubscriber) -> TrafficEvent {
    timeout(TEST_TIMEOUT, subscriber.recv())
        .await
        .expect("the proxy publishes an exchange")
        .expect("the event stream is healthy")
}

/// Waits for `count` exchanges, in the order they were published.
pub async fn next_exchanges(subscriber: &mut EventSubscriber, count: usize) -> Vec<TrafficEvent> {
    let mut exchanges = Vec::with_capacity(count);
    for _ in 0..count {
        exchanges.push(next_exchange(subscriber).await);
    }

    exchanges
}

/// The next captured WebSocket message or SSE event.
pub async fn next_stream_message(subscriber: &mut StreamSubscriber) -> StreamMessageSummary {
    timeout(TEST_TIMEOUT, subscriber.recv())
        .await
        .expect("the proxy publishes a stream message")
        .expect("the stream-message channel is healthy")
        .as_ref()
        .clone()
}

/// Asserts that no further exchange arrives.
///
/// Deliberately short: this is only ever used after an exchange that has
/// already been received, so anything else would already have been published.
pub async fn no_further_exchange(subscriber: &mut EventSubscriber) {
    let extra = timeout(Duration::from_millis(200), subscriber.recv()).await;

    assert!(
        extra.is_err(),
        "the proxy published an exchange that should not exist"
    );
}
