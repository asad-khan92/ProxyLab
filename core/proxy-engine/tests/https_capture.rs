//! End-to-end tests for traffic capture on the HTTPS interception path.
//!
//! The shape under test is the one interception is for:
//!
//! ```text
//! client --TLS #1--> proxy --HTTP/1.1--> proxy --TLS #2--> origin
//!                              ↑
//!                        this is what is captured
//! ```
//!
//! What is captured is the decrypted HTTP exchange, never a TLS byte, and it
//! is captured into the same model a plaintext request produces — so a
//! subscriber cannot tell from the model's shape which route a request took,
//! only from the scheme it names.
//!
//! Every certificate is generated by the test that needs it, from a CA
//! generated for that test. Nothing reads or writes a stored development CA,
//! and nothing reaches the network.

mod support;

use support::{
    next_exchange, no_further_exchange, origin_form_request, HttpsClient, Proxy, TlsOrigin,
    UntrustedTlsOrigin,
};

use proxy_engine::capture::Capture;
use proxy_storage::{CaptureConfig, EventPublisher, Scheme, TrafficError, TrafficErrorKind};

/// A plain `200 OK` with a body of known length.
const HELLO: &[u8] =
    b"HTTP/1.1 200 OK\r\nContent-Type: text/plain\r\nContent-Length: 12\r\n\r\nhello, https";

/// A capture that keeps at most `limit` bytes of each body.
fn capturing(limit: usize) -> Capture {
    Capture::new(CaptureConfig::new(limit), EventPublisher::new())
}

#[tokio::test]
async fn an_intercepted_request_publishes_a_completed_exchange() {
    let origin = TlsOrigin::responding_with("localhost", HELLO).await;
    let proxy = Proxy::trusting(origin.trust()).await;
    let mut events = proxy.events();
    let client = HttpsClient::trusting(proxy.trust());

    let response = client
        .exchange(
            proxy.addr(),
            &origin.authority(),
            origin.host(),
            &origin_form_request("GET", "/hello", &origin.authority(), &[]),
        )
        .await;
    assert_eq!(response.status, 200);

    let exchange = next_exchange(&mut events).await;

    assert!(exchange.succeeded(), "{}", exchange.summary());
    assert_eq!(exchange.request.method, "GET");
    assert_eq!(exchange.status(), Some(200));
    assert_eq!(exchange.connection.scheme, Scheme::Https);
    // The `CONNECT` that opened the session is not traffic of its own: the
    // request inside it is, and there is exactly one of them.
    no_further_exchange(&mut events).await;

    proxy.stop().await;
}

#[tokio::test]
async fn the_captured_url_is_the_https_url_the_client_asked_for() {
    let origin = TlsOrigin::responding_with("localhost", HELLO).await;
    let proxy = Proxy::trusting(origin.trust()).await;
    let mut events = proxy.events();
    let client = HttpsClient::trusting(proxy.trust());

    client
        .exchange(
            proxy.addr(),
            &origin.authority(),
            origin.host(),
            &origin_form_request("GET", "/api/users?active=true", &origin.authority(), &[]),
        )
        .await;

    let exchange = next_exchange(&mut events).await;

    // The request travelled inside the session in origin form; the capture
    // names the host the session was opened to, which is what a UI has to
    // show.
    assert_eq!(
        exchange.request.url,
        format!("https://{}/api/users?active=true", origin.authority())
    );
    assert_eq!(
        exchange
            .connection
            .destination
            .as_ref()
            .map(|destination| destination.host.as_str()),
        Some("localhost")
    );

    proxy.stop().await;
}

#[tokio::test]
async fn the_decrypted_request_headers_and_body_are_captured() {
    let origin = TlsOrigin::responding_with("localhost", HELLO).await;
    let proxy = Proxy::trusting(origin.trust()).await;
    let mut events = proxy.events();
    let client = HttpsClient::trusting(proxy.trust());

    let mut request = origin_form_request(
        "POST",
        "/users",
        &origin.authority(),
        &[
            ("Content-Type", "application/json"),
            ("Authorization", "Bearer sk-secret"),
            ("Content-Length", "14"),
        ],
    );
    request.extend_from_slice(br#"{"name":"ada"}"#);

    client
        .exchange(proxy.addr(), &origin.authority(), origin.host(), &request)
        .await;

    // The origin received the plaintext, and so did the capture.
    assert_eq!(origin.only_request().body_text(), r#"{"name":"ada"}"#);

    let exchange = next_exchange(&mut events).await;

    assert_eq!(exchange.request.method, "POST");
    assert_eq!(
        exchange.request.headers.text("content-type"),
        Some("application/json")
    );
    assert_eq!(
        exchange.request.headers.text("authorization"),
        Some("Bearer sk-secret")
    );
    // The decrypted body, not the TLS records it travelled in.
    assert_eq!(exchange.request.body.as_text(), Some(r#"{"name":"ada"}"#));
    assert_eq!(exchange.request.body.size(), 14);

    proxy.stop().await;
}

#[tokio::test]
async fn the_decrypted_response_headers_body_and_status_are_captured() {
    let origin = TlsOrigin::responding_with(
        "localhost",
        b"HTTP/1.1 201 Created\r\nLocation: /users/1\r\nSet-Cookie: session=abc\r\nContent-Length: 8\r\n\r\n{\"id\":1}",
    )
    .await;
    let proxy = Proxy::trusting(origin.trust()).await;
    let mut events = proxy.events();
    let client = HttpsClient::trusting(proxy.trust());

    let response = client
        .exchange(
            proxy.addr(),
            &origin.authority(),
            origin.host(),
            &origin_form_request("POST", "/users", &origin.authority(), &[]),
        )
        .await;
    assert_eq!(response.status, 201);

    let exchange = next_exchange(&mut events).await;
    let captured = exchange.response.as_ref().expect("a response was captured");

    assert_eq!(captured.status, 201);
    assert_eq!(captured.reason.as_deref(), Some("Created"));
    assert_eq!(captured.headers.text("location"), Some("/users/1"));
    assert_eq!(captured.headers.text("set-cookie"), Some("session=abc"));
    assert_eq!(captured.body.as_text(), Some(r#"{"id":1}"#));
    assert!(!captured.body.is_truncated());

    proxy.stop().await;
}

#[tokio::test]
async fn an_intercepted_exchange_is_timed_the_same_way_a_plaintext_one_is() {
    let origin = TlsOrigin::responding_with("localhost", HELLO).await;
    let proxy = Proxy::trusting(origin.trust()).await;
    let mut events = proxy.events();
    let client = HttpsClient::trusting(proxy.trust());

    client
        .exchange(
            proxy.addr(),
            &origin.authority(),
            origin.host(),
            &origin_form_request("GET", "/hello", &origin.authority(), &[]),
        )
        .await;

    let timing = next_exchange(&mut events).await.timing;

    assert!(timing.started_at.seconds > 1_600_000_000);
    let response = timing
        .upstream_response_micros
        .expect("the origin's answer was timed");
    let completed = timing.completed_micros.expect("the exchange was timed");
    assert!(response <= completed, "{response} > {completed}");

    // The connection to the origin was opened by the `CONNECT` that came
    // before this request, so there is no connect time to attribute to it.
    assert_eq!(timing.upstream_connect_micros, None);

    proxy.stop().await;
}

#[tokio::test]
async fn an_intercepted_body_over_the_limit_is_forwarded_in_full_and_captured_in_part() {
    let mut response = b"HTTP/1.1 200 OK\r\nContent-Length: 100000\r\n\r\n".to_vec();
    response.extend_from_slice(&vec![b'x'; 100_000]);
    let origin = TlsOrigin::start("localhost", move |_| response.clone()).await;
    let proxy = Proxy::capturing(origin.trust(), capturing(512)).await;
    let mut events = proxy.events();
    let client = HttpsClient::trusting(proxy.trust());

    let answered = client
        .exchange(
            proxy.addr(),
            &origin.authority(),
            origin.host(),
            &origin_form_request("GET", "/big", &origin.authority(), &[]),
        )
        .await;

    // The client received every byte; the capture kept the first 512.
    assert_eq!(answered.body().len(), 100_000);

    let exchange = next_exchange(&mut events).await;
    let captured = &exchange.response.as_ref().expect("a response").body;

    assert_eq!(captured.captured_len(), 512);
    assert_eq!(captured.size(), 100_000);
    assert!(captured.is_truncated());

    proxy.stop().await;
}

#[tokio::test]
async fn a_client_that_refuses_the_proxys_certificate_publishes_a_client_tls_failure() {
    let origin = TlsOrigin::responding_with("localhost", HELLO).await;
    let proxy = Proxy::trusting(origin.trust()).await;
    let mut events = proxy.events();
    let client = HttpsClient::trusting_nothing_local();

    let (connect, session) = client
        .connect(proxy.addr(), &origin.authority(), origin.host())
        .await;

    assert_eq!(connect.status, 200);
    session.expect_err("a client that has not installed the CA must not be fooled");

    // There was never an HTTP request to record, so the `CONNECT` is what is
    // published — otherwise a failed handshake would be traffic that simply
    // vanished.
    let exchange = next_exchange(&mut events).await;

    assert_eq!(exchange.request.method, "CONNECT");
    assert_eq!(exchange.request.url, origin.authority());
    assert_eq!(exchange.response, None);
    let error = exchange.error.as_ref().expect("a failure was captured");
    assert_eq!(error.kind(), TrafficErrorKind::ClientTls);
    assert_eq!(
        error.summary(),
        "the client did not accept the proxy's certificate"
    );

    proxy.stop().await;
}

#[tokio::test]
async fn an_origin_whose_certificate_is_not_trusted_publishes_an_upstream_tls_failure() {
    let origin = UntrustedTlsOrigin::start("localhost").await;
    // The proxy trusts only the public web PKI, which the origin's CA is not
    // in, so the origin's session is never established.
    let proxy = Proxy::start().await;
    let mut events = proxy.events();
    let client = HttpsClient::trusting(proxy.trust());

    let (connect, session) = client
        .connect(proxy.addr(), &origin.authority(), "localhost")
        .await;

    assert_eq!(connect.status, 200);
    session.expect("the client accepts the proxy's certificate");

    let exchange = next_exchange(&mut events).await;

    assert_eq!(exchange.request.method, "CONNECT");
    assert_eq!(exchange.response, None);
    let error = exchange.error.as_ref().expect("a failure was captured");
    assert_eq!(error.kind(), TrafficErrorKind::UpstreamTls);
    // A curated phrase: no certificate, cipher suite, or protocol detail
    // from the underlying TLS error is repeated into the capture.
    assert_eq!(
        error.summary(),
        "the TLS handshake with the destination server failed"
    );

    proxy.stop().await;
}

#[tokio::test]
async fn a_connect_to_a_destination_that_refuses_it_publishes_a_connect_failure() {
    let listener = tokio::net::TcpListener::bind("127.0.0.1:0")
        .await
        .expect("bind ephemeral port");
    let addr = listener.local_addr().expect("local address");
    drop(listener);

    let proxy = Proxy::start().await;
    let mut events = proxy.events();
    let client = HttpsClient::trusting(proxy.trust());

    let (connect, _) = client
        .connect(proxy.addr(), &addr.to_string(), "localhost")
        .await;
    assert_eq!(connect.status, 502);

    let exchange = next_exchange(&mut events).await;

    assert_eq!(
        exchange.error.as_ref().map(TrafficError::kind),
        Some(TrafficErrorKind::UpstreamConnect)
    );
    assert_eq!(
        exchange
            .connection
            .destination
            .as_ref()
            .map(|destination| destination.port),
        Some(addr.port())
    );

    proxy.stop().await;
}

#[tokio::test]
async fn an_intercepted_exchange_keeps_secrets_out_of_its_diagnostic_forms() {
    let origin = TlsOrigin::responding_with(
        "localhost",
        b"HTTP/1.1 200 OK\r\nSet-Cookie: session=s3cr3t-cookie\r\nContent-Length: 24\r\n\r\n{\"token\":\"s3cr3t-token\"}",
    )
    .await;
    let proxy = Proxy::trusting(origin.trust()).await;
    let mut events = proxy.events();
    let client = HttpsClient::trusting(proxy.trust());

    let mut request = origin_form_request(
        "POST",
        "/login",
        &origin.authority(),
        &[
            ("Authorization", "Bearer s3cr3t-bearer"),
            ("Cookie", "sid=s3cr3t-sid"),
            ("Content-Length", "30"),
        ],
    );
    request.extend_from_slice(br#"{"password":"s3cr3t-password"}"#);

    client
        .exchange(proxy.addr(), &origin.authority(), origin.host(), &request)
        .await;

    let exchange = next_exchange(&mut events).await;

    assert_eq!(
        exchange.request.body.as_text(),
        Some(r#"{"password":"s3cr3t-password"}"#)
    );

    for rendered in [format!("{exchange:?}"), exchange.summary()] {
        for secret in [
            "s3cr3t-bearer",
            "s3cr3t-sid",
            "s3cr3t-password",
            "s3cr3t-cookie",
            "s3cr3t-token",
        ] {
            assert!(
                !rendered.contains(secret),
                "a diagnostic rendering leaked {secret}: {rendered}"
            );
        }
    }

    proxy.stop().await;
}
